    claim_token                VARCHAR(36) COLLATE "C" NULL ,
    claim_expires_at           TIMESTAMP(6) WITH TIME ZONE                     NULL ,
    last_sent_at               TIMESTAMP(6) WITH TIME ZONE                     NULL ,
