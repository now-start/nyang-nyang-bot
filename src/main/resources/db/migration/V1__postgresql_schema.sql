CREATE TABLE command
(
    id                    BIGINT                          GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
    trigger_token         VARCHAR(20) COLLATE unicode_ci                     NOT NULL ,
    message_template      VARCHAR(1000) COLLATE unicode_ci                   NOT NULL ,
    is_active             BOOLEAN                         NOT NULL DEFAULT TRUE ,
    execution_policy      VARCHAR(32)                     NOT NULL DEFAULT 'USER_INTERVAL' COLLATE "C"
        ,
    user_cooldown_seconds INTEGER                         NULL DEFAULT 30 ,
    created_by_user_id    VARCHAR(64) COLLATE "C" NULL ,
    updated_by_user_id    VARCHAR(64) COLLATE "C" NULL ,
    created_at            TIMESTAMP(6) WITH TIME ZONE                     NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ,
    updated_at            TIMESTAMP(6) WITH TIME ZONE                     NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
         ,
    PRIMARY KEY (id),
    CONSTRAINT uk_command__trigger_token UNIQUE (trigger_token),
    CONSTRAINT fk_command__created_by_user
        FOREIGN KEY (created_by_user_id) REFERENCES user_account (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_command__updated_by_user
        FOREIGN KEY (updated_by_user_id) REFERENCES user_account (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_command__trigger_token
        CHECK (CHAR_LENGTH(trigger_token) BETWEEN 2 AND 20),
    CONSTRAINT ck_command__active
        CHECK (is_active IN (FALSE, TRUE)),
    CONSTRAINT ck_command__cooldown
        CHECK ((execution_policy = 'USER_INTERVAL'
                    AND user_cooldown_seconds IS NOT NULL
                    AND user_cooldown_seconds BETWEEN 5 AND 3600)
            OR (execution_policy = 'USER_CALENDAR_DAY'
                    AND user_cooldown_seconds IS NULL))
);
COMMENT ON COLUMN command.id IS '명령어 식별자';
COMMENT ON COLUMN command.trigger_token IS '채팅에서 명령어를 식별하는 토큰';
COMMENT ON COLUMN command.message_template IS '명령 실행 시 렌더링할 메시지 템플릿';
COMMENT ON COLUMN command.is_active IS '명령어 사용 여부';
COMMENT ON COLUMN command.execution_policy IS '사용자별 재실행 제한 기준';
COMMENT ON COLUMN command.user_cooldown_seconds IS '사용자별 재실행 제한 시간(초); 달력일 기준이면 NULL';
COMMENT ON COLUMN command.created_by_user_id IS '생성 사용자; NULL은 시스템 생성';
COMMENT ON COLUMN command.updated_by_user_id IS '최종 변경 사용자; NULL은 시스템 변경';
COMMENT ON COLUMN command.created_at IS '생성 시각';
COMMENT ON COLUMN command.updated_at IS '최종 변경 시각';
COMMENT ON TABLE command IS '사용자 정의 채팅 명령어';

CREATE TABLE command_execution
(
    id                        BIGINT                          GENERATED BY DEFAULT AS IDENTITY NOT NULL ,
    command_id                BIGINT                          NOT NULL ,
    user_id                   VARCHAR(64) COLLATE "C" NOT NULL ,
    executed_at               TIMESTAMP(6) WITH TIME ZONE                     NOT NULL ,
    execution_policy_snapshot VARCHAR(32) COLLATE "C" NOT NULL ,
    cooldown_seconds_snapshot INTEGER                         NULL ,
    calendar_day_started_at   TIMESTAMP(6) WITH TIME ZONE                     NULL ,
    PRIMARY KEY (id),
    CONSTRAINT uk_command_execution__command_user_day_start UNIQUE (command_id, user_id, calendar_day_started_at),
    CONSTRAINT fk_command_execution__command
        FOREIGN KEY (command_id) REFERENCES command (id) ON DELETE RESTRICT,
    CONSTRAINT fk_command_execution__user_account
        FOREIGN KEY (user_id) REFERENCES user_account (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_command_execution__policy
        CHECK ((execution_policy_snapshot = 'USER_INTERVAL'
                    AND cooldown_seconds_snapshot IS NOT NULL
                    AND cooldown_seconds_snapshot BETWEEN 5 AND 3600
                    AND calendar_day_started_at IS NULL)
            OR (execution_policy_snapshot = 'USER_CALENDAR_DAY'
                    AND cooldown_seconds_snapshot IS NULL
                    AND calendar_day_started_at IS NOT NULL
                    AND calendar_day_started_at <= executed_at))
);
CREATE INDEX idx_command_execution__user_command_time ON command_execution (user_id, command_id, executed_at, id);
COMMENT ON COLUMN command_execution.id IS '명령 실행 이벤트 식별자';
COMMENT ON COLUMN command_execution.command_id IS '실행한 명령어 식별자';
COMMENT ON COLUMN command_execution.user_id IS '명령을 실행한 사용자 식별자';
COMMENT ON COLUMN command_execution.executed_at IS '명령 실행 확정 절대시각';
COMMENT ON COLUMN command_execution.execution_policy_snapshot IS '실행 시점의 사용자별 재실행 제한 기준 스냅샷';
COMMENT ON COLUMN command_execution.cooldown_seconds_snapshot IS '실행 시점의 사용자별 재실행 제한 초 스냅샷; 달력일 기준이면 NULL';
COMMENT ON COLUMN command_execution.calendar_day_started_at IS 'Asia/Seoul 달력일 시작 절대시각; 달력일 기준에서만 저장';
COMMENT ON TABLE command_execution IS '전체·사용자별 횟수와 일별 연속 실행을 계산하는 명령 실행 이벤트';

